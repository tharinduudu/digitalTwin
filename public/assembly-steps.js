export function visibleAtStep(partStep, currentStep, showComplete = false) {
  return showComplete || partStep <= currentStep;
}

export function smoothAssembly(progress) {
  const t = Math.max(0, Math.min(1, progress));
  return t * t * (3 - 2 * t);
}
