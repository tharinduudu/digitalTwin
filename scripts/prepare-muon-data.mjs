import { writeFile } from 'node:fs/promises';

const source = 'https://pdg.lbl.gov/2024/AtomicNuclearProperties/MUE/muE_polystyrene.txt';
const response = await fetch(source);
if (!response.ok) throw new Error(`PDG table: HTTP ${response.status}`);
const rows = (await response.text()).split('\n')
  .filter(line => /^\s+\d\.\d+E[+-]\d+/.test(line))
  .map(line => line.trim().split(/\s+/).map(Number))
  .filter(row => row.length === 12 && row[0] >= 10)
  .map(row => [row[0], row[7], row[8]]);
if (rows.length < 80 || rows.some(row => row.some(value => !Number.isFinite(value)))) {
  throw new Error('Unexpected PDG table format');
}
const header = `// Generated by scripts/prepare-muon-data.mjs from ${source}\n`
  + '// Columns: kinetic energy (MeV), total mean stopping power (MeV cm2/g), CSDA range (g/cm2).\n';
await writeFile(new URL('../public/polystyrene-data.js', import.meta.url),
  header + `export const STOPPING_TABLE = ${JSON.stringify(rows)};\n`);
console.log(`Saved ${rows.length} PDG polystyrene rows`);
